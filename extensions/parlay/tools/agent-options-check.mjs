import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { runInNewContext } from 'node:vm';
import ts from 'typescript';
import { modeInstructions } from '../src/agentModes.ts';
const source = fs.readFileSync(new URL('../src/agentOptions.ts', import.meta.url), 'utf8');
const exports = {};
runInNewContext(ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, { exports, require: name => ({ vscode: {}, fs, os, path })[name] });
const options = { model: 'my-model', effort: 'high', fast: true };
const codex = exports.optionArgs('gpt', options);
assert.ok(codex.includes('my-model'));
assert.ok(codex.includes('model_reasoning_effort="high"'));
assert.ok(codex.includes('service_tier="fast"'));
const claude = exports.optionArgs('claude', options);
assert.equal(claude[claude.indexOf('--effort') + 1], 'high');
assert.equal(JSON.parse(claude[claude.indexOf('--settings') + 1]).fastMode, true);
assert.ok(exports.optionArgs('gpt', { ...options, fast: false }).includes('service_tier="default"'));
const modes = modeInstructions(path.resolve(import.meta.dirname, '..'));
assert.match(modes, /CAVEMAN MODE: lite/);
assert.match(modes, /PONYTAIL MODE: full/);
assert.match(modes, /Keep articles \+ full sentences/);
assert.ok(!modes.includes('| **ultra** |'));
// Inline code must remain literal even when it contains Markdown syntax.
const js = fs.readFileSync(new URL('../media/chat.js', import.meta.url), 'utf8');
const inline = js.slice(js.indexOf('function inline(s)'), js.indexOf('\nlet state'));
const scope = { esc: s => String(s).replace(/[&<>"]/g, c => ({ '&':'&amp;', '<':'&lt;', '>':'&gt;', '"':'&quot;' })[c]) };
runInNewContext(inline, scope);
assert.equal(scope.inline('`**literal**`'), '<code>**literal**</code>');
assert.equal(scope.inline('`<script>`'), '<code>&lt;script&gt;</code>');
assert.equal(scope.inline('**bold**'), '<b>bold</b>');
console.log('Agent controls: model/effort/fast flags, pinned modes and inline-code formatting passed');
